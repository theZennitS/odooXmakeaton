export function getRolePermissions(
  matrix: DocPermissionMatrix,
  role: UserRole
): DocPermissionRule[] {
  return matrix.filter((rule) => rule.role === role);
}

export function checkDocPermission(
  matrix: DocPermissionMatrix,
  role: UserRole,
  docType: string,
  action: keyof Omit<DocPermissionRule, "doc_type" | "role">
): boolean {
  const rule = matrix.find(
    (r) => r.role === role && r.doc_type.toLowerCase() === docType.toLowerCase()
  );
  return rule ? Boolean(rule[action]) : false;
}
